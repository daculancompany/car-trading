<?php

namespace App\Http\Controllers;

use App\Models\Customer;
use App\Helpers\NotificationHelper;
use App\Models\User;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Storage;
use Illuminate\Validation\Rule;

class CustomerController extends Controller
{
    private const IMAGE_RULES = [
        'nullable',
        'image',
        'mimes:jpeg,jpg,png,webp',
        'max:5120',
    ];

    /**
     * Display all customers.
     */
    public function index(): JsonResponse
    {
        $customers = Customer::with('user.role')
            ->latest()
            ->get();

        return response()->json([
            'message' => 'Customers retrieved successfully.',
            'data' => $customers,
        ], 200);
    }

    /**
     * Register a new customer.
     */
    public function store(Request $request): JsonResponse
    {
        $validated = $request->validate([
            // User account
            'username' => [
                'required',
                'string',
                'max:255',
                'unique:users,username',
            ],

            'email' => [
                'required',
                'email',
                'max:255',
                'unique:users,email',
            ],

            'password' => [
                'required',
                'string',
                'min:8',
                'confirmed',
            ],

            // Customer information
            'first_name' => [
                'required',
                'string',
                'max:255',
            ],

            'middle_name' => [
                'nullable',
                'string',
                'max:255',
            ],

            'last_name' => [
                'required',
                'string',
                'max:255',
            ],

            'suffix' => [
                'nullable',
                'string',
                'max:255',
            ],

            'address' => [
                'required',
                'string',
                'max:255',
            ],

            'civil_status' => [
                'required',
                Rule::in([
                    'single',
                    'married',
                    'widowed',
                    'separated',
                ]),
            ],

            'employment_type' => [
                'required',
                Rule::in([
                    'employed',
                    'self_employed',
                ]),
            ],

            'mobile_number' => [
                'required',
                'string',
                'max:20',
            ],

            'facebook' => [
                'required',
                'string',
                'max:255',
            ],

            'image' => self::IMAGE_RULES,
        ]);

        $imagePath = $request->hasFile('image')
            ? $request->file('image')->store('customers', 'public')
            : null;

        $customer = DB::transaction(function () use ($validated, $imagePath) {

            /*
             * Find the Customer role.
             */
            $customerRole = \App\Models\Role::where(
                'name',
                'Customer'
            )->firstOrFail();

            /*
             * Create user account.
             */
            $user = User::create([
                'role_id' => $customerRole->id,
                'email' => $validated['email'],
                'username' => $validated['username'],
                'password' => Hash::make($validated['password']),
                'is_active' => true,
            ]);

            /*
             * Create customer profile.
             */
            return Customer::create([
                'user_id' => $user->id,

                'first_name' => $validated['first_name'],
                'middle_name' => $validated['middle_name'] ?? null,
                'last_name' => $validated['last_name'],
                'suffix' => $validated['suffix'] ?? null,

                'address' => $validated['address'],
                'civil_status' => $validated['civil_status'],
                'employment_type' => $validated['employment_type'],

                'mobile_number' => $validated['mobile_number'],
                'facebook' => $validated['facebook'],
                'image_path' => $imagePath,

                // Automatically generated by backend
                'date_registered' => now()->toDateString(),

                'is_active' => true,
            ]);
        });

        /*
         * Load relationships.
         */
        $customer->load('user.role');

        return response()->json([
            'message' => 'Customer registered successfully.',
            'data' => $customer,
        ], 201);
    }

    /**
     * Display a specific customer.
     */
    public function show(Customer $customer): JsonResponse
    {
        $customer->load('user.role');

        return response()->json([
            'message' => 'Customer retrieved successfully.',
            'data' => $customer,
        ], 200);
    }

    /**
     * Update a customer.
     */
    public function update(
        Request $request,
        Customer $customer
    ): JsonResponse {
        $validated = $request->validate([
            'first_name' => [
                'sometimes',
                'required',
                'string',
                'max:255',
            ],

            'middle_name' => [
                'nullable',
                'string',
                'max:255',
            ],

            'last_name' => [
                'sometimes',
                'required',
                'string',
                'max:255',
            ],

            'suffix' => [
                'nullable',
                'string',
                'max:255',
            ],

            'address' => [
                'sometimes',
                'required',
                'string',
                'max:255',
            ],

            'civil_status' => [
                'sometimes',
                'required',
                Rule::in([
                    'single',
                    'married',
                    'widowed',
                    'separated',
                ]),
            ],

            'employment_type' => [
                'sometimes',
                'required',
                Rule::in([
                    'employed',
                    'self_employed',
                ]),
            ],

            'mobile_number' => [
                'sometimes',
                'required',
                'string',
                'max:20',
            ],

            'facebook' => [
                'sometimes',
                'required',
                'string',
                'max:255',
            ],

            'is_active' => [
                'sometimes',
                'boolean',
            ],
        ]);

        $customer->update($validated);

        $customer->load('user.role');

        return response()->json([
            'message' => 'Customer updated successfully.',
            'data' => $customer->fresh('user.role'),
        ], 200);
    }

    public function updatePhoto(Request $request, Customer $customer): JsonResponse
    {
        return $this->savePhoto($request, $customer);
    }

    public function updateMyPhoto(Request $request): JsonResponse
    {
        $customer = $request->user()->customer;

        abort_if(!$customer, 404, 'No customer profile found.');

        return $this->savePhoto($request, $customer);
    }

    private function savePhoto(Request $request, Customer $customer): JsonResponse
    {
        $request->validate([
            'image' => ['required_without:remove', ...self::IMAGE_RULES],
            'remove' => ['sometimes', 'boolean'],
        ]);

        if ($customer->image_path) {
            Storage::disk('public')->delete($customer->image_path);
        }

        $customer->update([
            'image_path' => $request->hasFile('image')
                ? $request->file('image')->store('customers', 'public')
                : null,
        ]);

        return response()->json([
            'message' => $customer->image_path ? 'Photo updated successfully.' : 'Photo removed.',
            'data' => $customer->fresh('user.role'),
        ], 200);
    }

    /**
     * Archive a customer.
     */
    public function destroy(Customer $customer): JsonResponse
    {
        /**
         * Cannot Archive If Reservations Exist
         */
        if ($customer->reservations()->exists()) {
            return response()->json([
                'message' =>
                'This customer cannot be archived because they have existing reservations.',
            ], 409);
        }

        DB::transaction(function () use ($customer) {

            /**
             * Get Associated User
             */
            $user = $customer->user;

            /**
             * Archive Customer Profile
             */
            $customer->update([
                'archived' => 1,
            ]);

            /**
             * Archive User Account
             */
            if ($user) {
                $user->update([
                    'archived' => 1,
                ]);
            }
        });

        return response()->json([
            'message' => 'Customer archived successfully.',
        ], 200);
    }
}
